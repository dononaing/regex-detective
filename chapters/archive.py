import re
from base import Round


class ArchiveRound(Round):
    def __init__(self, title, description, examples, hint, clue, test_cases):
        super().__init__(title, description, examples, hint, clue)
        # test_cases — список кортежей: (текст_сообщения, [ожидаемые_совпадения])
        self.test_cases = test_cases

    def check(self, pattern):
        try:
            compiled = re.compile(pattern)
        except re.error as err:
            return False, f"Ошибка в синтаксисе регулярного выражения: {err}. Попробуйте ещё раз."

        for text, expected in self.test_cases:
            # По требованию задания используем re.finditer() и сравниваем полные совпадения и их порядок
            actual = [match.group(0) for match in compiled.finditer(text)]
            if actual != expected:
                return (
                    False,
                    f"Ошибка при проверке архивной записи:\n"
                    f"«{text}»\n"
                    f"Ожидалось найти: {expected}\n"
                    f"Ваш шаблон нашёл: {actual}\n"
                    f"Попробуйте скорректировать выражение."
                )

        return True, "Отлично! Все архивные номера дел извлечены без единой ошибки."


def get_archive_rounds():
    round_1 = ArchiveRound(
        title="Архив Скотланд-Ярда: Шифры Лестрейда",
        description=(
            "Инспектор Лестрейд передал Холмсу выписки из телеграмм Скотланд-Ярда.\n"
            "Найдите в тексте все номера уголовных дел, пропустив даты и номера кэбов.\n"
            "Формат номера дела: слово CASE, дефис, ровно 4 цифры (например, CASE-1887)."
        ),
        examples=(
            "Текст: «14.10.1895 в 22:15 кэб № 4021 выехал по делу CASE-1887, связано с CASE-0042.»\n"
            "Ожидаемый результат: ['CASE-1887', 'CASE-0042']"
        ),
        hint="Используйте слово CASE-, а затем квантификатор {4} для четырёх цифр \\d (не забудьте границы слова \\b, чтобы не захватить лишние цифры).",
        clue="Записка с Бейкер-стрит: «Подозреваемый сдал багаж в камеру хранения № 221B перед отъездом в Дувр».",
        test_cases=[
            # Видимый пример из условия
            (
                "14.10.1895 в 22:15 кэб № 4021 выехал по делу CASE-1887, связано с CASE-0042.",
                ["CASE-1887", "CASE-0042"],
            ),
            # Скрытые проверочные примеры
            (
                "Отчёт от 01.05.1891: старое дело CASE-9910 закрыто, но CASE-12345 — это опечатка, а CASE-12 слишком короткий.",
                ["CASE-9910"],
            ),
            (
                "В архиве за 1894 год фигурируют только CASE-7701, CASE-7702 и CASE-7703.",
                ["CASE-7701", "CASE-7702", "CASE-7703"],
            ),
            (
                "Запись от 12.11.1895: упоминаний нужных дел нет, только счёт на 1500 фунтов.",
                [],
            ),
        ],
    )

    round_2 = ArchiveRound(
        title="Архив переписки: Тайные досье Майкрофта",
        description=(
            "В переписке клуба «Диоген» упоминаются секретные досье.\n"
            "Извлеките все коды досье, игнорируя даты, время и денежные суммы.\n"
            "Формат кода: две заглавные латинские буквы, дефис, 3 цифры, дефис и одна заглавная буква (например, SH-221-B)."
        ),
        examples=(
            "Текст: «Встреча 03.11.1895 в 19:00. Передать папки SH-221-B и JM-007-X. Бюджет 500 фунтов.»\n"
            "Ожидаемый результат: ['SH-221-B', 'JM-007-X']"
        ),
        hint="Шаблон строится по схеме: две заглавные буквы [A-Z]{2}, дефис, три цифры \\d{3}, дефис, одна заглавная буква [A-Z], с границами слова \\b по краям.",
        clue="Ключ от сейфа в клубе «Диоген» с гравировкой «Профессор М. — Рейхенбах».",
        test_cases=[
            # Видимый пример из условия
            (
                "Встреча 03.11.1895 в 19:00. Передать папки SH-221-B и JM-007-X. Бюджет 500 фунтов.",
                ["SH-221-B", "JM-007-X"],
            ),
            # Скрытые проверочные примеры
            (
                "Ложные коды: sh-221-b (нижний регистр), ABC-123-D (три буквы в начале), AB-12-C (мало цифр), XY-999-Z1 (лишняя цифра). Верный: MW-404-A.",
                ["MW-404-A"],
            ),
            (
                "Телеграмма от 18.12.1895: срочно поднять архивы IR-101-A, JW-505-C и SL-880-K.",
                ["IR-101-A", "JW-505-C", "SL-880-K"],
            ),
            (
                "Обычная сводка погоды в Лондоне на 20.12.1895: туман, видимость 15 ярдов.",
                [],
            ),
        ],
    )

    return [round_1, round_2]


if __name__ == "__main__":
    r1, r2 = get_archive_rounds()

    # Проверка раунда 1
    assert r1.check(r"\bCASE-\d{4}\b")[0] is True, "Верный шаблон для раунда 1 должен приниматься"
    assert r1.check(r"\d{4}")[0] is False, "Шаблон, цепляющий годы и номера кэбов, должен отклоняться"
    assert r1.check(r"[unclosed")[0] is False, "Синтаксическая ошибка не должна ронять программу"

    # Проверка раунда 2
    assert r2.check(r"\b[A-Z]{2}-\d{3}-[A-Z]\b")[0] is True, "Верный шаблон для раунда 2 должен приниматься"
    assert r2.check(r"[A-Z]+-\d+-[A-Z]+")[0] is False, "Слишком широкий шаблон должен отклоняться"
    assert r2.check(r"*invalid*")[0] is False, "Синтаксическая ошибка не должна ронять программу"

    print("Все проверки assert для chapters/archive.py успешно пройдены!")